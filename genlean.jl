# Generate the Lean proof from a core (profiles), its CNF (same order as build()), and the trimmed LRAT proof.
# usage: julia genlean.jl core.txt h trimmed.cnf trimmed.lrat trimmed.map out.lean
include("explore.jl")
function main()
corefile, hs, tcnf, tlrat, tmap, out = ARGS
h = parse(Int, hs)
core = [Tuple(parse.(Int, split(l))) for l in eachline(corefile) if !isempty(strip(l))]

# rebuild clauses exactly as build() does, with provenance
P = [mkprof(p, h) for p in core]
var = Vector{NTuple{N,Int}}(undef, length(P)); nv = 0
for a in eachindex(P); var[a] = ntuple(i -> P[a].fr[i] ? (nv += 1) : 0, N); end
varinfo = Dict{Int,Tuple{Int,Int}}()            # var -> (profile, state)
for a in eachindex(P), i in 1:N; var[a][i] != 0 && (varinfo[var[a][i]] = (a, i)); end
prov = Any[]; clauses = Vector{Vector{Int}}()
for a in eachindex(P)
    fi = [var[a][i] for i in 1:N if P[a].fr[i]]
    for m in 0:(2^length(fi) - 1)
        count_ones(m) == P[a].k && continue
        push!(clauses, [((m >> (t - 1)) & 1 == 1) ? -fi[t] : fi[t] for t in eachindex(fi)]); push!(prov, (:quota, a))
    end
end
for a in eachindex(P), b in eachindex(P)
    a == b && continue
    p, q = P[a].p, P[b].p
    for i in 1:N, j in 1:N
        (i != j && q[i] >= p[i] && q[j] <= p[j]) || continue
        for ai in vals(P[a], i), bi in vals(P[b], i), aj in vals(P[a], j), bj in vals(P[b], j)
            (bi < ai && bj > aj) || continue
            lits = [eqlit(P[a], i, ai, var[a]), eqlit(P[b], i, bi, var[b]), eqlit(P[a], j, aj, var[a]), eqlit(P[b], j, bj, var[b])]
            any(==(:false), lits) && continue
            push!(clauses, unique(Int[-l for l in lits if l isa Int])); push!(prov, (:pm, a, b, i, j))
        end
    end
end
# trimmed map
ml = readlines(tmap)
newvar_old = Dict{Int,Int}()
keep = Int[]
for l in ml
    if startswith(l, "clauses"); keep = parse.(Int, split(l)[2:end])
    else; a, b = parse.(Int, split(l)); newvar_old[a] = b; end
end
tcl = [parse.(Int, split(l)[1:end-1]) for l in readlines(tcnf)[2:end]]
@assert length(tcl) == length(keep)
for (k, old) in enumerate(keep)   # sanity: trimmed clause equals original after var map
    @assert sort([sign(x) * newvar_old[abs(x)] for x in tcl[k]]) == sort(clauses[old]) "clause mismatch $k"
end
nvt = length(newvar_old)

vec4(p) = "![" * join(p, ", ") * "]"
prof(a) = "P$(a)"
atom(v) = (ai = varinfo[v]; "(f $(prof(ai[1])) $h $(ai[2]-1) = $(P[ai[1]].fl[ai[2]] + 1))")

io = IOBuffer()
println(io, """
import Mathlib

set_option linter.unusedVariables false

/-!
# Quota and population monotonicity are incompatible for four states at a fixed house size

Auto-generated by `genlean.jl` (see `PROOF.md`).  House size $h, $(length(core)) population profiles.
-/

namespace Apportion4

/-- Quota: the solution allocates exactly `h` seats and every state gets the floor or the
ceiling of its standard quota `h * p i / ∑ p`. -/
def Quota (f : (Fin 4 → ℕ) → ℕ → Fin 4 → ℕ) : Prop :=
  ∀ (p : Fin 4 → ℕ) (h : ℕ), (∀ k, 0 < p k) →
    (∑ i, f p h i = h) ∧
    ∀ i, f p h i = h * p i / (∑ j, p j) ∨ f p h i = (h * p i + (∑ j, p j) - 1) / (∑ j, p j)

/-- Population monotonicity, with both compared inputs at the same house size `h`
(Robinson–Ullman / Gölz–Peters–Procaccia definition, restricted to `h' = h`):
if state `i` weakly grew and state `j` weakly shrank, then `i` does not lose a seat while
`j` gains one. -/
def PopMonoFixedHouse (f : (Fin 4 → ℕ) → ℕ → Fin 4 → ℕ) : Prop :=
  ∀ (p p' : Fin 4 → ℕ) (h : ℕ) (i j : Fin 4), (∀ k, 0 < p k) → (∀ k, 0 < p' k) → i ≠ j →
    p i ≤ p' i → p' j ≤ p j → ¬ (f p' h i < f p h i ∧ f p h j < f p' h j)
""")
for a in eachindex(P)
    println(io, "abbrev $(prof(a)) : Fin 4 → ℕ := $(vec4(core[a]))")
end
# per-profile facts
for a in eachindex(P)
    pa = P[a]
    parts = String[]
    for i in 1:N
        fl = pa.fl[i]
        push!(parts, pa.fr[i] ? "(f $(prof(a)) $h $(i-1) = $fl ∨ f $(prof(a)) $h $(i-1) = $(fl+1))" : "f $(prof(a)) $h $(i-1) = $fl")
    end
    push!(parts, "f $(prof(a)) $h 0 + f $(prof(a)) $h 1 + f $(prof(a)) $h 2 + f $(prof(a)) $h 3 = $h")
    println(io, """
theorem fact$(a) {f : (Fin 4 → ℕ) → ℕ → Fin 4 → ℕ} (hq : Quota f) :
    $(join(parts, " ∧\n    ")) := by
  obtain ⟨hs, hi⟩ := hq $(prof(a)) $h (by decide)
  generalize f $(prof(a)) $h = g at hs hi ⊢
  have h0 := hi 0; have h1 := hi 1; have h2 := hi 2; have h3 := hi 3
  simp only [Fin.sum_univ_four, $(prof(a)), Matrix.cons_val_zero, Matrix.cons_val_one,
    Matrix.cons_val_two, Matrix.cons_val_three] at hs h0 h1 h2 h3
  norm_num at h0 h1 h2 h3
  omega
""")
end
# clause lemmas: hypothesis = falsifier conjunction (as produced by lrat_proof), conclusion False
function falsifier(c)   # lrat reify: positive literal -> ¬atom, negative -> atom ; right-nested ∧
    fs = [x > 0 ? "¬$(atom(x))" : atom(-x) for x in c]
    join(fs, " ∧ ")
end
for (k, old) in enumerate(keep)
    c = clauses[old]; pv = prov[old]
    hyp = falsifier(c)
    ats = [x > 0 ? x : -x for x in c]
    if pv[1] == :quota
        a = pv[2]
        body = "  have := fact$(a) hq\n  omega"
    else
        _, a, b, i, j = pv
        body = "  have := fact$(a) hq\n  have := fact$(b) hq\n" *
               "  have := hpm $(prof(a)) $(prof(b)) $h $(i-1) $(j-1) (by decide) (by decide) (by decide) (by decide) (by decide)\n  omega"
    end
    println(io, """
theorem cl$(k) {f : (Fin 4 → ℕ) → ℕ → Fin 4 → ℕ} (hq : Quota f) (hpm : PopMonoFixedHouse f) :
    ¬ ($(hyp)) := by
  intro hc
$(body)
""")
end
# lrat theorem
cnfstr = read(tcnf, String); lratstr = read(tlrat, String)
println(io, "lrat_proof refutation\n  \"$(replace(cnfstr, "\n" => " "))\"\n  \"$(replace(lratstr, "\n" => " "))\"\n")
# rcases pattern for balanced tree over clauses 1..m
function pat(s, e)   # [s, e)
    len = e - s
    len == 1 && return "h$(s)"
    mid = s + len ÷ 2
    "(" * pat(s, mid) * " | " * pat(mid, e) * ")"
end
m = length(keep)
atomsargs = join([atom(newvar_old[v] |> identity) for v in 1:nvt], " ")
# careful: atom expects old var id
atomsargs = join([atom(newvar_old[v]) for v in 1:nvt], " ")
println(io, """
/-- **Main theorem.** No deterministic four-state apportionment solution satisfies both quota and
population monotonicity when monotonicity is only required between inputs with the same house size. -/
theorem no_quota_popmono_fixed_house :
    ¬ ∃ f : (Fin 4 → ℕ) → ℕ → Fin 4 → ℕ, Quota f ∧ PopMonoFixedHouse f := by
  rintro ⟨f, hq, hpm⟩
  rcases refutation $(atomsargs) with $(pat(1, m + 1))""")
for k in 1:m
    println(io, "  · exact cl$(k) hq hpm h$(k)")
end
println(io, "\nend Apportion4")
write(out, take!(io))
println("written $out: clauses $m vars $nvt profiles $(length(core))")
end
main()
